    /** 等级判定 */
    public static function gradeOf(float|int $total): string
    {
        if ($total >= 85) {
            return '优秀';
        }
        if ($total >= 71) {
            return '合格';
        }
        if ($total >= 61) {
            return '基本合格';
        }

        return '不合格';
    }

